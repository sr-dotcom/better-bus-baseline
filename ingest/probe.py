"""Write data/probe.md: service-date coverage and comparison-date counts per feed, from bbb.duckdb.

Run from the repo root after loading: uv run python -m ingest.probe
"""

from datetime import date

import duckdb

from ingest.calendar import active_service_ids
from ingest.load_gtfs import FEEDS, ROOT

DATES = [
    date(2026, 9, 30),
    date(2026, 10, 14),
    date(2026, 9, 26),
    date(2026, 10, 17),
    date(2026, 9, 27),
    date(2026, 10, 18),
]
# Dates each feed is meant to cover; zero trips on any of these is a stop condition.
EXPECTED = {
    "2026-09-10": {date(2026, 9, 26), date(2026, 9, 27), date(2026, 9, 30)},
    "2026-09-29": {date(2026, 9, 30), date(2026, 10, 14), date(2026, 10, 17), date(2026, 10, 18)},
}


def has_table(con, name):
    return con.execute("select count(*) from information_schema.tables where table_name = ?", [name]).fetchone()[0] > 0


def counts(con, version, day):
    ids = sorted(active_service_ids(con, version, day))
    if not ids:
        return 0, 0, 0
    q = "select count(distinct trip_id), count(distinct route_id) from raw_trips where feed_version = ? and service_id = any(?)"
    trips, routes = con.execute(q, [version, ids]).fetchone()
    return len(ids), trips, routes


def main() -> None:
    con = duckdb.connect(str(ROOT / "data/bbb.duckdb"), read_only=True)
    out = [
        "# Probe",
        "",
        "Generated by `ingest/probe.py` from `data/bbb.duckdb`. Dates are service dates (local calendar dates).",
        "",
    ]
    out += [
        "## Service date range",
        "",
        "| feed_version | calendar.txt rows | min date | max date |",
        "| --- | --- | --- | --- |",
    ]
    for v in FEEDS:
        n_cal = (
            con.execute("select count(*) from raw_calendar where feed_version = ?", [v]).fetchone()[0]
            if has_table(con, "raw_calendar")
            else 0
        )
        union = "select date as d from raw_calendar_dates where feed_version = ?"
        params = [v]
        if n_cal:
            union += " union all select start_date from raw_calendar where feed_version = ? union all select end_date from raw_calendar where feed_version = ?"
            params += [v, v]
        lo, hi = con.execute(f"select min(d), max(d) from ({union})", params).fetchone()
        out.append(f"| {v} | {n_cal} | {lo} | {hi} |")
    out += [
        "",
        "## Comparison dates",
        "",
        "| date | weekday | feed_version | service_ids | trips | routes |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    failures = []
    for d in DATES:
        for v in FEEDS:
            s, t, r = counts(con, v, d)
            note = "" if d in EXPECTED[v] else " (not covered by this feed)"
            out.append(f"| {d} | {d:%a} | {v}{note} | {s} | {t} | {r} |")
            if d in EXPECTED[v] and t == 0:
                failures.append((v, d))
    out += ["", "## Other checks", ""]
    for v in FEEDS:
        if has_table(con, "raw_frequencies"):
            n = con.execute("select count(*) from raw_frequencies where feed_version = ?", [v]).fetchone()[0]
            out.append(f"- {v}: frequencies.txt present, {n} rows")
        else:
            out.append(f"- {v}: frequencies.txt not in the feed")
    for v in FEEDS:
        n = con.execute(
            "select count(*) from raw_trips where feed_version = ? and coalesce(trim(direction_id), '') = ''", [v]
        ).fetchone()[0]
        out.append(f"- {v}: trips with empty direction_id: {n}")
    (ROOT / "data/probe.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    if failures:
        raise SystemExit(f"STOP: zero trips on expected dates: {failures}")


if __name__ == "__main__":
    main()
